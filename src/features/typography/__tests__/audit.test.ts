import { describe, expect, it } from "vitest";
import { typograph } from "../pipeline";
import { PRESETS } from "../presets";

const russian = PRESETS.find((p) => p.id === "russian")!;

const options = { enabledRules: russian.enabledRules, protection: {} };

/** Все сравнения — в нормализованном виде (NBSP → пробел). */
function t(input: string): string {
  return typograph(input, options).text.replace(/\u00A0/g, " ");
}

/**
 * Регрессии по итогам аудита: 10 некорректных текстов + вторая партия
 * коварных случаев. Каждый пункт — найденная или проверенная проблема.
 */
describe("Аудит: кавычки", () => {
  it("готовые „лапки“ нормализуются в ёлочки целиком (обе кавычки)", () => {
    expect(t("„лапки“")).toBe("«лапки»");
  });

  it("разнобой «…“ нормализуется в ёлочки", () => {
    expect(t("«смешанное“")).toBe("«смешанное»");
  });

  it("английская пара “…” → «…»", () => {
    expect(t("Он сказал “привет” и ушёл.")).toBe("Он сказал «привет» и ушёл.");
  });

  it("незакрытая открывающая кавычка закрывается", () => {
    expect(t('незакрытая кавычка "мир и открытые «скобки (внутри)')).toBe(
      "незакрытая кавычка «мир и открытые „скобки (внутри)“»",
    );
  });
});

describe("Аудит: тире и дефисы", () => {
  it("«наконец - то» склеивается в «наконец-то»", () => {
    expect(t('...и вот он "пришёл - наконец - то" домой.')).toBe(
      "… и вот он «пришёл — наконец-то» домой.",
    );
  });

  it("повтор слова «тихо - тихо» склеивается дефисом, а не тире", () => {
    expect(t('Он крикнул "Стой!!", но потом "тихо - тихо" ушёл.')).toBe(
      "Он крикнул «Стой!!», но потом «тихо-тихо» ушёл.",
    );
  });

  it("разные слова через дефис остаются тире", () => {
    expect(t("Любишь - кататься")).toBe("Любишь — кататься");
  });

  it("двойной дефис -- → тире", () => {
    expect(t("это -- так")).toBe("это — так");
  });
});

describe("Аудит: прочее", () => {
  it("валюты: $20, € 30, £5, $ 55", () => {
    expect(t("Цена $20 и € 30 и £5. Итого $ 55.")).toBe("Цена $20 и €30 и £5. Итого $55.");
  });

  it("пустые скобки схлопываются", () => {
    expect(t("текст ( ) конец и (  ) ещё.")).toBe("текст () конец и () ещё.");
  });

  it("маркер списка в начале строки не превращается в тире диалога... или превращается консистентно", () => {
    // plain-текст: реплика диалога; поведение задокументировано.
    expect(t("- Пункт один")).toBe("— Пункт один");
  });

  it("короткое слово в конце строки стягивается со следующей строкой", () => {
    // Проверяем исходный текст без нормализации NBSP: перенос после «и»
    // заменяется неразрывным пробелом.
    expect(typograph("Мама мыла раму и\nстекло в раме.", options).text).toBe(
      "Мама мыла раму и\u00A0стекло в\u00A0раме.",
    );
  });

  it("температура с уже набранным °C не дублируется", () => {
    expect(t("10°C и 5°C")).toBe("10 °C и 5 °C");
  });

  it("даты, версии, IP, файлы не трогаются", () => {
    expect(
      t("С 01.01.2026 по 31.12.2026 выходные. Версия 1.2.3, IP 192.168.0.1, файл report.psd."),
    ).toBe("С 01.01.2026 по 31.12.2026 выходные. Версия 1.2.3, IP 192.168.0.1, файл report.psd.");
  });

  it("email, URL и inline-код защищены", () => {
    expect(t("письмо на example@mail.ru, сайт http://test.ru/a?b=1 и код `x - y`.")).toBe(
      "письмо на example@mail.ru, сайт http://test.ru/a?b=1 и код `x - y`.",
    );
  });

  it("идемпотентность: повторный прогон не меняет текст", () => {
    const samples = [
      'Он сказал: "Фраза "мы говорим о "втором уровне" вложенности" звучит сложно".',
      "Кто - то из нас, а точнее 2 - 3 человека, промёрзли на -10 градусов.",
      "Звони +7 ( 999 ) 123 - 45 - 67, заезжай после 12:00.",
      "…и вот он «пришёл — наконец-то» домой.",
      "„лапки“ и “английские” и «ёлочки».",
    ];
    for (const sample of samples) {
      const first = typograph(sample, options).text;
      const second = typograph(first, options);
      expect(second.changed, `не идемпотентно: ${first}`).toBe(false);
    }
  });
});
