/**
 * Регрессии аудита сложных текстов: ложные срабатывания, порча смайлов
 * и склейка строк. Каждый кейс закрывает конкретный найденный дефект.
 */
describe("Регрессии: ложные срабатывания и структура", () => {
  it("смайлы с носом и скобкой не разрываются", () => {
    expect(t("Смайл :) и :( не трогаем.")).toBe(
      `Смайл :) и${NBSP}:( не${NBSP}трогаем.`,
    );
    expect(t("Смайл :-( и =( тоже.")).toBe(`Смайл :-( и${NBSP}=( тоже.`);
  });

  it("инициалы в конце строки не склеивают строки", () => {
    expect(t("Доклад подготовил И. И.\nПетров для конференции.")).toBe(
      `Доклад подготовил${NBSP}И.${NBSP}И.\nПетров для${NBSP}конференции.`,
    );
  });

  it("незакрытая кавычка закрывается в конце содержательной строки", () => {
    expect(t('Он начал: "В пути\n')).toBe(`Он начал: «В${NBSP}пути»\n`);
  });

  it("числа с ведущим нулём не разбиваются на разряды", () => {
    expect(t("Код 0000012 в базе.")).toBe(`Код 0000012 в${NBSP}базе.`);
    expect(t("Ввод 1000000 чисел")).toContain(`1${NBSP}000${NBSP}000`);
  });

  it("слова с буквой сокращения на конце не считаются сокращениями", () => {
    expect(t("На складе сад.5 тонн.")).toBe(`На${NBSP}складе сад.5 тонн.`);
    expect(t("Ряд.5 домов на улице.")).toBe(`Ряд.5 домов на${NBSP}улице.`);
  });

  it("настоящие сокращения по-прежнему работают", () => {
    expect(t("Адрес: ул.Ленина, д.5, оф.12.")).toBe(
      `Адрес: ул. Ленина, д.${NBSP}5, оф.${NBSP}12.`,
    );
  });
});

/**
 * Регрессии стресс-текста: смесь «плохих» пробелов, телефонов, единиц
 * и скобок в одном абзаце. Каждый кейс — из реального прогона.
 */
describe("Регрессии: стресс-текст", () => {
  it("дробь перед процентом приводится к запятой", () => {
    expect(t("Коэффициент составил 0.5 % ( через точку ) .")).toBe(
      "Коэффициент составил 0,5% (через точку).",
    );
  });

  it("метры квадратные и кубические получают пробел и надстрочный индекс", () => {
    expect(t("площадь 1500м2 разместили")).toBe(`площадь 1500${NBSP}м\u00B2 разместили`);
    expect(t("объём 12м3 воды")).toBe(`объём 12${NBSP}м\u00B3 воды`);
  });

  it("слэш между единицами пишется без пробелов", () => {
    expect(t("до 100 Мбит / сек .")).toBe(`до${NBSP}100${NBSP}Мбит/сек.`);
  });

  it("телефон со случайными пробелами нормализуется", () => {
    expect(t("Телефон для справок : +7 ( 999 ) 123 - 45 - 67 .")).toBe(
      `Телефон для${NBSP}справок: +7 (999) 123-45-67.`,
    );
    expect(t("Звоните 8(999)1234567 !")).toBe("Звоните 8 (999) 123-45-67!");
  });

  it("точка перед скобкой не слипается с ней", () => {
    expect(t("45 - 67 .( Примечание автора : текст ) .")).toBe(
      `45${EN_DASH}67. (Примечание автора: текст).`,
    );
  });

  it("диапазон из точек между числами превращается в многоточие", () => {
    expect(t("Длина кабеля 10...12 см")).toBe(`Длина кабеля 10${ELLIPSIS}12${NBSP}см`);
  });

  it("нумерованный список и абзацы не склеиваются в простыню", () => {
    const input = "Абзац один.\n\nСписок:\n1. Первый пункт\n2. Второй пункт";
    expect(t(input)).toBe(input);
  });

  it("предлог перед переносом строки стягивается со следующей строкой", () => {
    expect(t("находится в\nсамом центре")).toBe(`находится в${NBSP}самом центре`);
  });
});