import { describe, expect, it } from "vitest";
import { typograph } from "../pipeline";
import { PRESETS } from "../presets";

const russian = PRESETS.find((p) => p.id === "russian")!;

const options = { enabledRules: russian.enabledRules, protection: {} };

/** Все сравнения — в нормализованном виде (NBSP → пробел). */
function t(input: string): string {
  return typograph(input, options).text.replace(/\u00A0/g, " ");
}

describe("Кавычки: двусмысленные закрытия (регрессия «кавычки-убийцы»)", () => {
  it("закрывающая кавычка после пробела не превращается в открывающую „", () => {
    expect(t('статье " Новые технологии в 2026 году " .')).toBe(
      "статье «Новые технологии в 2026 году».",
    );
  });

  it("название организации в кавычках после пробела", () => {
    expect(t('директор ООО " Ромашка " г-н Иванов')).toBe(
      "директор ООО «Ромашка» г-н Иванов",
    );
  });

  it("прямая речь с кавычкой перед точкой", () => {
    expect(t('Он сказал : "Мы должны всё сделать " .')).toBe(
      "Он сказал: «Мы должны всё сделать».",
    );
  });

  it("короткая реплика с пробелами внутри кавычек", () => {
    expect(t('" О , да ! " - воскликнул он .')).toBe(
      "«О, да!» — воскликнул он.",
    );
  });

  it("последовательность двусмысленных кавычек балансируется парами", () => {
    expect(t('" раз " раз " раз "')).toBe("«раз» раз «раз»");
  });

  it("вложенная прямая речь внутри ёлочек", () => {
    expect(t('"Он сказал: "Привет""')).toBe("«Он сказал: „Привет“»");
  });

  it("дюймы (цифра + кавычка) остаются как есть", () => {
    expect(t('Экран 24" и IPS')).toBe('Экран 24" и IPS');
  });
});

describe("Тире: перечислительные наречия", () => {
  it("Во-вторых-найти → Во-вторых — найти", () => {
    expect(t("Во-вторых-найти инвесторов")).toBe("Во-вторых — найти инвесторов");
  });

  it("В-третьих-запустить → В-третьих — запустить", () => {
    expect(t("В-третьих-запустить рекламу")).toBe("В-третьих — запустить рекламу");
  });

  it("дефис внутри сложных слов не трогается", () => {
    expect(t("красно-белый флаг и во-вторых аккаунт")).toBe(
      "красно-белый флаг и во-вторых аккаунт",
    );
  });
});

describe("Скобки: пробел перед открывающей скобкой", () => {
  it("команда(состоящая → команда (состоящая", () => {
    expect(t("наша команда(состоящая из людей)")).toBe(
      "наша команда (состоящая из людей)",
    );
  });

  it("латинские вызовы вида f(x) не трогаются", () => {
    expect(t("вызов f(x) в коде")).toBe("вызов f(x) в коде");
  });

  it("скобка после пробела не дублирует пробел", () => {
    expect(t("текст (примечание)")).toBe("текст (примечание)");
  });
});

describe("Время: ЧЧ:ММ", () => {
  it("15 : 30 → 15:30", () => {
    expect(t("встреча на 15 : 30")).toBe("встреча на 15:30");
  });

  it("15: 30 → 15:30 (после правила пробелов)", () => {
    expect(t("встреча на 15: 30")).toBe("встреча на 15:30");
  });

  it("9 : 05 → 9:05", () => {
    expect(t("в 9 : 05 утра")).toBe("в 9:05 утра");
  });

  it("не время (хвост числа) не трогается", () => {
    expect(t("код 115: 30")).toBe("код 115: 30");
  });

  it("одиночная цифра после двоеточия — не время", () => {
    expect(t("соотношение 1 : 2")).toBe("соотношение 1: 2");
  });
});

describe("Краш-тест пользователя (полный текст)", () => {
  const source = [
    'Вступление к статье " Новые технологии в 2026 году " . Это был жаркий день,когда директор ООО " Ромашка " г-н Иванов И.И. решил запустить проект стоимостью 1000000$ . Он сказал : "Мы должны внедрить ИИ , робототехнику и т. д. в наше производство " .',
    "",
    "На дворе стоял XXI век... Или все-таки 21-й век ? В любом случае ,наша команда( состоящая из 5-и человек ) начала работу . Координаты офиса: г. Москва , ул. Ленина , д. 10 , кв. 5. Телефон для связи : +7(999)123-45-67.",
    "",
    "Вот основные пункты нашего плана :",
    "- Во-первых , надо изучить рынок .",
    "- Во-вторых-найти инвесторов .",
    "- В-третьих, запустить рекламу .",
    "",
    'Маркетолог Петров А. В. утверждал , что 50% успеха зависит от пиара . " О , да ! " - воскликнул он . Мы использовали графики ( см. рис. 1 ) , чтобы доказать это боссу . Кстати , встреча назначена на 15 : 30 , не опоздайте !',
    "",
    "Проблемы, с которыми мы столкнулись :",
    "1. Нехватка времени ( всего 2-3 месяца )",
    "2. Маленький бюджет -- около 5000 рублей .",
    "3. Технические неполадки в т.ч. падение сервера .",
    "",
    "В итоге , в 2025-2026 гг. мы смогли достичь цели на все 100 % . Это победа ! Или нет ?.. Узнаем в следующей серии . Конец текста . ",
  ].join("\n");

  const result = typograph(source, options).text;
  const plain = result.replace(/\u00A0/g, " ");

  it("нет стеков незакрытых кавычек в конце", () => {
    expect(plain.trimEnd()).toMatch(/Конец текста\.$/);
    expect(plain).not.toMatch(/»{2,}/);
    expect(plain).not.toMatch(/“{2,}/);
    expect(plain).not.toMatch(/„\./);
  });

  it("кавычки встали парными ёлочками", () => {
    expect(plain).toContain("статье «Новые технологии в 2026 году».");
    expect(plain).toContain("ООО «Ромашка»");
    expect(plain).toContain(
      "«Мы должны внедрить ИИ, робототехнику и т. д. в наше производство».",
    );
    expect(plain).toContain("«О, да!» — воскликнул он.");
  });

  it("наречия, скобки и время исправлены", () => {
    expect(plain).toContain("- Во-первых, надо изучить рынок.");
    expect(plain).toContain("- Во-вторых — найти инвесторов.");
    expect(plain).toContain("- В-третьих, запустить рекламу.");
    expect(plain).toContain("команда (состоящая из 5-и человек)");
    expect(plain).toContain("на 15:30, не опоздайте!");
  });

  it("идемпотентность: повторная обработка ничего не меняет", () => {
    const twice = typograph(result, options).text;
    expect(twice).toBe(result);
  });
});

