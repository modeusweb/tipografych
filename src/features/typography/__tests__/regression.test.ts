import { describe, expect, it } from "vitest";
import { typograph } from "../pipeline";
import { PRESETS } from "../presets";

const russian = PRESETS.find((p) => p.id === "russian")!;

const options = { enabledRules: russian.enabledRules, protection: {} };

/** Все сравнения — в нормализованном виде (NBSP → пробел). */
function t(input: string): string {
  return typograph(input, options).text.replace(/\u00A0/g, " ");
}

describe("Кавычки: двусмысленные закрытия (регрессия «кавычки-убийцы»)", () => {
  it("закрывающая кавычка после пробела не превращается в открывающую „", () => {
    expect(t('статье " Новые технологии в 2026 году " .')).toBe(
      "статье «Новые технологии в 2026 году».",
    );
  });

  it("название организации в кавычках после пробела", () => {
    expect(t('директор ООО " Ромашка " г-н Иванов')).toBe(
      "директор ООО «Ромашка» г-н Иванов",
    );
  });

  it("прямая речь с кавычкой перед точкой", () => {
    expect(t('Он сказал : "Мы должны всё сделать " .')).toBe(
      "Он сказал: «Мы должны всё сделать».",
    );
  });

  it("короткая реплика с пробелами внутри кавычек", () => {
    expect(t('" О , да ! " - воскликнул он .')).toBe(
      "«О, да!» — воскликнул он.",
    );
  });

  it("последовательность двусмысленных кавычек балансируется парами", () => {
    expect(t('" раз " раз " раз "')).toBe("«раз» раз «раз»");
  });

  it("вложенная прямая речь внутри ёлочек", () => {
    expect(t('"Он сказал: "Привет""')).toBe("«Он сказал: „Привет“»");
  });

  it("дюймы (цифра + кавычка) остаются как есть", () => {
    expect(t('Экран 24" и IPS')).toBe('Экран 24" и IPS');
  });
});

describe("Тире: перечислительные наречия", () => {
  it("Во-вторых-найти → Во-вторых — найти", () => {
    expect(t("Во-вторых-найти инвесторов")).toBe("Во-вторых — найти инвесторов");
  });

  it("В-третьих-запустить → В-третьих — запустить", () => {
    expect(t("В-третьих-запустить рекламу")).toBe("В-третьих — запустить рекламу");
  });

  it("дефис внутри сложных слов не трогается", () => {
    expect(t("красно-белый флаг и во-вторых аккаунт")).toBe(
      "красно-белый флаг и во-вторых аккаунт",
    );
  });
});

describe("Аудит №2: разорванные дефисы, расширения, точка после кавычки", () => {
  it("разорванное дефисное слово склеивается, а не превращается в тире", () => {
    expect(t("Вряд ли кто - то заметит разницу")).toBe("Вряд ли кто-то заметит разницу");
  });

  it("дефис с пробелом только после тоже склеивается («как- либо»)", () => {
    expect(t("как- либо")).toBe("как-либо");
    expect(t("во- первых")).toBe("во-первых");
    expect(t("что- то заметил")).toBe("что-то заметил");
  });

  it("тире между словами остаётся тире", () => {
    expect(t("Он не пришёл - то есть соврал")).toBe("Он не пришёл — то есть соврал");
  });

  it("голые расширения файлов не разбиваются пробелом", () => {
    expect(t("макеты в формате .psd или .fig")).toBe("макеты в формате .psd или .fig");
  });

  it("точка после закрывающей кавычки убирается, если цитата уже завершена", () => {
    expect(t('сдать объект " к 10-му числу " .')).toBe("сдать объект «к 10-му числу».");
    expect(t('написано : " Дней ... " .')).toBe("написано: «Дней…»");
  });
});

describe("Аудит №3: латинские префиксы, температура, единицы, диапазон в скобках", () => {
  it("латинский префикс склеивается дефисом, тире-сказуемое не трогается", () => {
    expect(t("Проблемы в IT - индустрии")).toBe("Проблемы в IT-индустрии");
    expect(t("HTTP - это протокол")).toBe("HTTP — это протокол");
  });

  it("устойчивое сочетание «как попало» остаётся раздельным", () => {
    expect(t("пишут текст как попало")).toBe("пишут текст как попало");
    expect(t("собрано как попало")).toBe("собрано как попало");
  });

  it("знаковая температура с пробелом и кириллической «С» нормализуется", () => {
    expect(t("знак цельсия ( +25 С )")).toBe("знак цельсия (+25 °C)");
    expect(t("было -10 С ночью")).toBe("было −10 °C ночью");
  });

  it("диапазон в скобках сжимается до en-dash", () => {
    expect(t("тире ( 5—10 ).")).toBe("тире (5–10).");
    expect(t("тире ( 5 - 10 ).")).toBe("тире (5–10).");
  });

  it("точка после «кг» убирается внутри предложения и остаётся в конце", () => {
    expect(t("или даже 15кг. веса")).toBe("или даже 15 кг веса");
    expect(t("весил 15 кг. Конец")).toBe("весил 15 кг. Конец");
  });
});


