import { describe, expect, it } from "vitest";
import { typograph } from "../pipeline";
import { PRESETS } from "../presets";

const russian = PRESETS.find((p) => p.id === "russian")!;

const options = { enabledRules: russian.enabledRules, protection: {} };

/** Все сравнения — в нормализованном виде (NBSP → пробел). */
function t(input: string): string {
  return typograph(input, options).text.replace(/\u00A0/g, " ");
}

/**
 * Аудит-2: 20 кривых текстов из интернета.
 *
 * Источники: smoke-тесты и тесты правил typograf/typograf
 * (test/smoke.ru.test.ts, src/rules/ru/money, src/rules/ru/dash),
 * «Ководство» Артемия Лебедева (§ 63, § 71, § 116) и страница
 * типографа Студии Артемия Лебедева. NBSP нормализуется в пробел.
 */
describe("Аудит-2 (typograf, Ководство): телефоны и время", () => {
  it("слитный 11-значный номер форматируется как телефон", () => {
    expect(t("тел.: 88001004888, доб. 123")).toBe("тел.: 8 (800) 100-48-88, доб. 123");
    expect(t("+74951004888")).toBe("+7 (495) 100-48-88");
  });

  it("длинные последовательности цифр, не похожие на телефон, не трогаются", () => {
    // Разряды режутся справа налево, числа не с 8/+7 телефонами не считаются.
    expect(t("индекс 1800100488 и артикул 98001004888")).toBe(
      "индекс 1 800 100 488 и артикул 98 001 004 888",
    );
  });

  it("«9-00» — время, а не диапазон «от 9 до нуля»; «13-14» — диапазон", () => {
    expect(t("звоните с 9-00 до 18-00, обед с 13-14")).toBe(
      "звоните с 9:00 до 18:00, обед с 13–14",
    );
  });
});

describe("Аудит-2 (typograf, Ководство): римские века", () => {
  it("склеенный диапазон веков получает короткое тире", () => {
    expect(t("в XVI-XVII веках")).toBe("в XVI\u2013XVII веках");
  });

  it("разорванный диапазон веков, включая уже набранное длинное тире", () => {
    expect(t("в XX - XXI веках всё изменилось")).toBe("в XX\u2013XXI веках всё изменилось");
    expect(t("XVIII — XIX вв.")).toBe("XVIII\u2013XIX вв.");
  });

  it("аббревиатуры из римских букв без контекста веков не трогаются", () => {
    expect(t("артикулы LCD и MIX, модель DIM")).toBe("артикулы LCD и MIX, модель DIM");
    expect(t("в XVI-XVII веках, но RANGE MIX")).toBe("в XVI\u2013XVII веках, но RANGE MIX");
  });

  it("годы по-прежнему работают", () => {
    expect(t("в 1600-1699 гг.")).toBe("в 1600–1699 гг.");
  });
});

describe("Аудит-2 (typograf, Ководство): рубль", () => {
  it("короткая форма «р.» после числа становится ₽", () => {
    expect(t("У меня 100 р., а у тебя 200 р. и 50 долл.")).toBe(
      "У меня 100 ₽, а у тебя 200 ₽ и 50 долл.",
    );
    expect(t("Цена 100р. или 200р.?")).toBe("Цена 100 ₽ или 200 ₽?");
  });

  it("«руб.» перед пунктуацией тоже становится ₽", () => {
    expect(t("Цена 5000 руб., а переписка - 200 р.")).toBe("Цена 5000 ₽, а переписка — 200 ₽.");
  });

  it("суммы с копейками не трогаются", () => {
    expect(t("Сдал 100 р. 20 коп. мелочью")).toBe("Сдал 100 р. 20 коп. мелочью");
    expect(t("Сдал 100 руб. 20 коп. мелочью")).toBe("Сдал 100 руб. 20 коп. мелочью");
  });

  it("точка сокращения съедается перед строчной, сохраняется перед заглавной", () => {
    expect(t("100 руб. и 200 руб.")).toBe("100 ₽ и 200 ₽.");
    expect(t("100 руб. И ещё 200 руб.")).toBe("100 ₽. И ещё 200 ₽.");
  });

  it("знак ₽ без пробела отбивается неразрывным пробелом", () => {
    const out = typograph("всего 100₽ и 5000₽", options).text;
    expect([...out].map((c) => (c === "\u00A0" ? "␣" : c)).join("")).toBe(
      "всего 100␣₽ и␣5000␣₽",
    );
  });

  it("«Знак рубля всегда должен стоять с отбивкой от числа» (Ководство § 159)", () => {
    expect(t("Знак рубля всегда должен стоять с отбивкой от числа: 100₽, 5000 руб., 200 р.")).toBe(
      "Знак рубля всегда должен стоять с отбивкой от числа: 100 ₽, 5000 ₽, 200 ₽.",
    );
  });
});

describe("Аудит-2 (typograf, Ководство): годы и даты", () => {
  it("диапазон годов с единственным «г.» переводится в «гг.»", () => {
    expect(t("Проект (2012-2015 г.) завершён")).toBe("Проект (2012–2015 гг.) завершён");
    expect(t("2012-2015 гг. уже верно")).toBe("2012–2015 гг. уже верно");
  });

  it("диапазоны дней месяца (тест typograf daysMonth)", () => {
    expect(t("Акция: 1-22 сентября принимаем заявки")).toBe("Акция: 1–22 сентября принимаем заявки");
  });

  it("адрес и дата из smoke-теста typograf", () => {
    expect(t("ваш адрес: Россия, г. Саратов, дом 25 - исправьте до 01.02.2026г.")).toBe(
      "ваш адрес: Россия, г. Саратов, дом 25 — исправьте до 01.02.2026 г.",
    );
  });
});

describe("Аудит-2: идемпотентность интернет-текстов", () => {
  it("повторный прогон не меняет текст", () => {
    const samples = [
      "тел.: 88001004888, доб. 123; звоните с 9-00 до 18-00, обед с 13-14.",
      'Это "Типограф"? Нет, это "Типограф" - сервис... быстро.',
      "В XVI-XVII веках, а точнее в 1600-1699 гг., в XX - XXI веках всё изменилось.",
      'Проект "Дом - сад" (2012-2015 г.) - совместная работа с ООО "Ромашка".',
      "Знак рубля всегда должен стоять с отбивкой от числа: 100₽, 5000 руб., 200 р.",
      "У меня 100 р., а у тебя 200 р. и 50 долл.",
      "Разрешение изменилось: было 640 x 480, а стало 1024 x 768.",
    ];
    for (const sample of samples) {
      const first = typograph(sample, options).text;
      const second = typograph(first, options);
      expect(second.changed, `не идемпотентно: ${first}`).toBe(false);
    }
  });
});
