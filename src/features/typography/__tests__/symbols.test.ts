import { describe, expect, it } from "vitest";
import { typograph } from "../pipeline";
import { PRESETS } from "../presets";

/**
 * Тесты «символьных» правил: знаки ©, ®, ™, дроби, знак умножения,
 * стрелки, схлопывание пустых строк и сокращение года.
 * Ожидания учитывают весь конвейер, а не отдельное правило.
 */

const russian = PRESETS.find((p) => p.id === "russian")!;

const options = { enabledRules: russian.enabledRules, protection: {} };

const NBSP = "\u00A0";
const COPY = "\u00A9";
const REG = "\u00AE";
const TM = "\u2122";
const TIMES = "\u00D7";
const ARROW_RIGHT = "\u2192";
const ARROW_LEFT = "\u2190";
const ARROW_BOTH = "\u21D4";
const RUBLE = "\u20BD";

/** Результат с нормализованными неразрывными пробелами. */
function t(input: string): string {
  return typograph(input, options).text.replace(/\u00A0/g, " ");
}

/** Результат «как есть» (для проверки неразрывных пробелов). */
function raw(input: string): string {
  return typograph(input, options).text;
}

describe("Знаки ©, ®, ™", () => {
  it("(c), (r) и (tm) заменяются символами", () => {
    expect(t("Зарегистрированная марка (R) или торговый знак (TM).")).toBe(
      `Зарегистрированная марка ${REG} или торговый знак ${TM}.`,
    );
    expect(t("Авторское право (c) 2026.")).toBe(`Авторское право ${COPY} 2026.`);
  });

  it("кириллические (с) и (тм) тоже распознаются", () => {
    expect(t("Знак (с) и (тм) набран в русской раскладке.")).toBe(
      `Знак ${COPY} и ${TM} набран в русской раскладке.`,
    );
  });

  it("пробелы внутри скобок не мешают: «( c )» → «(c)» → ©", () => {
    expect(t("Авторское право ( c ) 2026.")).toBe(`Авторское право ${COPY} 2026.`);
  });

  it("в формулах переменные в скобках не заменяются", () => {
    // «(c)» рядом со знаком операции — переменная, а не знак охраны прав.
    expect(t("По формуле A ( c ) = B + C.")).toBe("По формуле A (c) = B + C.");
    expect(t("Значение 2 * (c) больше нуля.")).toBe("Значение 2 * (c) больше нуля.");
  });

  it("уже готовые символы остаются на месте", () => {
    const text = `${COPY} 2026, ${REG} и ${TM}`;
    expect(t(text)).toBe(text);
  });
});

describe("Обыкновенные дроби", () => {
  it("простые дроби становятся символами", () => {
    expect(t("Дробь 1/2 или 3/4 должна превратиться в символ.")).toBe(
      "Дробь \u00BD или \u00BE должна превратиться в символ.",
    );
    expect(t("Возьми 1/4 и 1/3.")).toBe("Возьми \u00BC и \u2153.");
  });

  it("неизвестная дробь остаётся как есть", () => {
    expect(t("Отношение 5/7 к целому.")).toBe("Отношение 5/7 к целому.");
  });

  it("конструкции с буквами и защищённые фрагменты не трогаются", () => {
    expect(t("Скорость до 100 Мбит/сек.")).toBe("Скорость до 100 Мбит/сек.");
    expect(t("Адрес https://example.com/1/2 в тексте.")).toContain(
      "https://example.com/1/2",
    );
    expect(t("Код `1/2` не дробь.")).toContain("`1/2`");
  });

  it("дроби, примыкающие к числам и слэшам, не трогаются", () => {
    expect(t("Код 11/2 в базе.")).toBe("Код 11/2 в базе.");
    expect(t("Путь 1/2/3 описан.")).toBe("Путь 1/2/3 описан.");
  });

  it("пробелы вокруг слэша схлопываются: «1 / 2» → «½»", () => {
    expect(t("Также проверим дроби: 1 / 2 или 3 / 4 .")).toBe(
      `Также проверим дроби: \u00BD или \u00BE.`,
    );
  });
});

describe("Знак умножения", () => {
  it("кириллическая «х» между числами заменяется на ×", () => {
    expect(t("Длина стороны равна 5х5 см.")).toBe(`Длина стороны равна 5${TIMES}5 см.`);
  });

  it("латинская «x» между числами заменяется на ×", () => {
    expect(t("Формат 10x10 пикселей.")).toBe(`Формат 10${TIMES}10 пикселей.`);
    expect(t("Размер 2X2 метра.")).toBe(`Размер 2${TIMES}2 метра.`);
  });

  it("hex-литералы не превращаются в умножение", () => {
    expect(t("Адрес 0x1F в памяти.")).toBe("Адрес 0x1F в памяти.");
  });

  it("буква на границе слова не трогается", () => {
    expect(t("Купили 2х-комнатную квартиру.")).toBe("Купили 2х-комнатную квартиру.");
  });
});

describe("Плюс-минус и степени", () => {
  it("«+-» и «+/-» становятся знаком ±", () => {
    expect(t("5 +- 3 = 8")).toBe("5 \u00B1 3 = 8");
    expect(t("5 +/- 3")).toBe("5 \u00B1 3");
  });

  it("обычное сложение не трогается", () => {
    expect(t("5 + 3 = 8")).toBe("5 + 3 = 8");
  });

  it("степень через «^» становится верхним индексом", () => {
    expect(t("10^8")).toBe("10\u2078");
    expect(t("2^-3")).toBe("2\u207B\u00B3");
  });

  it("математическая запись целиком", () => {
    expect(t("Скорость света равна c = 3 x 10^8 м / с .")).toBe(
      `Скорость света равна c = 3${TIMES}10\u2078 м/с.`,
    );
  });
});

describe("Стрелки", () => {
  it("текстовые стрелки заменяются символами", () => {
    expect(t("Путь -> к цели.")).toBe(`Путь ${ARROW_RIGHT} к цели.`);
    expect(t("Обратно <- домой.")).toBe(`Обратно ${ARROW_LEFT} домой.`);
    expect(t("Смысл <=> равенство.")).toBe(`Смысл ${ARROW_BOTH} равенство.`);
  });

  it("составные последовательности не трогаются", () => {
    expect(t("Код --> и <<- не трогаем.")).toBe("Код --> и <<- не трогаем.");
  });
});

describe("Пустые строки", () => {
  it("лишние пустые строки схлопываются до одной", () => {
    expect(t("Абзац.\n\n\n\n\nКонец.")).toBe("Абзац.\n\nКонец.");
  });

  it("абзацы и одиночные переносы сохраняются", () => {
    expect(t("Абзац один.\n\nАбзац два.\nСтрока стиха.")).toBe(
      "Абзац один.\n\nАбзац два.\nСтрока стиха.",
    );
  });
});

describe("Сокращение года", () => {
  it("после даты ставится неразрывный пробел", () => {
    expect(raw("Это произошло 01.01.2026г. в г.Москва.")).toBe(
      `Это произошло 01.01.2026${NBSP}г. в${NBSP}г. Москва.`,
    );
  });

  it("диапазон годов с «гг.» тоже отбивается", () => {
    expect(t("В 2025-2026гг. мы выросли.")).toBe("В 2025\u20132026 гг. мы выросли.");
  });

  it("год без даты: «в 2026г.» → «в 2026 г.»", () => {
    expect(t("Это было в 2026г.")).toBe("Это было в 2026 г.");
  });

  it("пробел перед «г.» приводится к неразрывному", () => {
    expect(raw("В 2026 г. всё изменилось.")).toBe(
      `В${NBSP}2026${NBSP}г. всё изменилось.`,
    );
  });

  it("«5-го числа» не считается годом", () => {
    expect(t("Ждём 5-го числа.")).toBe("Ждём 5-го числа.");
  });
});

describe("Валюты", () => {
  it("текстовые обозначения рубля после числа становятся знаком ₽", () => {
    expect(raw(`Цены выросли на 90руб.`)).toBe(`Цены выросли на${NBSP}90${NBSP}${RUBLE}.`);
    expect(t("Бюджет проекта 5000 рублей")).toBe(`Бюджет проекта 5000 ${RUBLE}`);
    expect(t("Курс 100 руб. или 90 рублей")).toBe(`Курс 100 ${RUBLE} или 90 ${RUBLE}`);
  });

  it("слово «рубль» без числа не трогается", () => {
    expect(t("Один рубль остался в кармане.")).toBe("Один рубль остался в кармане.");
  });

  it("знаки валют по умолчанию пишутся слитно с числом", () => {
    expect(raw("Цена 5000$ за штуку.")).toBe(`Цена 5000$ за${NBSP}штуку.`);
    expect(raw("Доллар $5 или €50 в кассе.")).toBe(`Доллар $5 или${NBSP}€50 в${NBSP}кассе.`);
  });

  it("отбивка знаков валют — опция «Издательской»", () => {
    const publisher = PRESETS.find((p) => p.id === "publisher")!;
    const result = typograph("Цена 5000$ и 4300000€.", {
      enabledRules: publisher.enabledRules,
      protection: {},
    });
    expect(result.text).toBe(`Цена 5000${NBSP}$ и${NBSP}4${NBSP}300${NBSP}000${NBSP}€.`);
  });

  it("буквенные обозначения валют отбиваются от числа", () => {
    expect(raw("Цена 100долл. или 50грн.")).toBe(`Цена 100${NBSP}долл. или${NBSP}50${NBSP}грн.`);
    expect(raw("Всего 20евро и 300тенге.")).toBe(`Всего 20${NBSP}евро и${NBSP}300${NBSP}тенге.`);
  });

  it("слова, начинающиеся как валюта, не трогаются", () => {
    expect(t("Здесь 100долларовый кредит.")).toBe("Здесь 100долларовый кредит.");
  });

  it("позиция валюты после числа — только в «Издательской»", () => {
    const publisher = PRESETS.find((p) => p.id === "publisher")!;
    const result = typograph("Курс $100 и €50 сегодня.", {
      enabledRules: publisher.enabledRules,
      protection: {},
    });
    expect(result.text).toBe(`Курс 100${NBSP}$ и${NBSP}50${NBSP}€ сегодня.`);
  });

  it("пробел между знаком валюты и числом убирается", () => {
    expect(t("Данный знак стоит всего $ 100")).toBe("Данный знак стоит всего $100");
    expect(t("цена 100 $")).toBe("цена 100$");
  });
});

describe("Идемпотентность новых правил", () => {
  it("повторная обработка ничего не меняет", () => {
    const inputs = [
      "Длина 5х5 см и дробь 1/2 или 3/4.",
      "Путь -> цель <- назад <=> равно.",
      "Авторское право (c) 2026, марка (R), знак (TM).",
      "Авторское право ( c ) 2026 и формула A ( c ) = B + C.",
      "Событие 01.01.2026г. и период 2025-2026гг.",
      "Абзац.\n\n\n\n\nКонец.",
      "Цена 5000$ или 90руб. за штуку.",
      "Температура -10°C и стандарт ISO-8601.",
      "Курс $100 и €50 сегодня.",
    ];
    for (const input of inputs) {
      const once = typograph(input, options).text;
      expect(typograph(once, options).text).toBe(once);
    }
  });
});