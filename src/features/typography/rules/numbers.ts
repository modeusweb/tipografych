import type { TypographyRule } from "../types";
import { applyRegex } from "./helpers";

/**
 * Разделители разрядов в числах: «1000000» → «1 000 000»
 * (неразрывный пробел). Спорное правило — выключено по умолчанию,
 * включается пресетами «Русская типографика» и «Издательская».
 *
 * Защита от ложных срабатываний:
 *  - числа короче 5 цифр не трогаются (годы «2025» остаются целыми);
 *  - телефоны, даты, IP, версии и артикулы защищены токенами раньше;
 *  - числа, примыкающие к буквам/цифрам/двоеточию, пропускаются.
 */
export const numbersThousandsRule: TypographyRule = {
  id: "numbers-thousands",
  name: "Разделители разрядов",
  description:
    "Разбивает числа из 5+ цифр по разрядам неразрывным пробелом («1000000» → «1 000 000»). Годы, телефоны, даты и версии не трогаются.",
  category: "numbers",
  enabledByDefault: false,
  apply(text, ctx) {
    return applyRegex(
      ctx,
      numbersThousandsRule,
      text,
      // Числа с ведущим нулём («00001», коды и артикулы) не разбиваются:
      // это идентификаторы, а не количества.
      /(?<![\p{L}\p{N}:/=])(?<!\d\.)(?!0)\d{5,}(?![\p{L}\p{N}:])/gu,
      (m) => m[0].replace(/\B(?=(\d{3})+(?!\d))/g, "\u00A0"),
    );
  },
};
