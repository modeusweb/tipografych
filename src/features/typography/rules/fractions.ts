import type { TypographyRule } from "../types";
import { applyRegex } from "./helpers";

/**
 * Таблица простых дробей: ASCII-запись → типографский символ.
 * Только однозначные случаи («1/2», «3/4» и т. п.).
 * В комментариях указаны кодовые точки символов — так их видно в
 * любом редакторе и они не зависят от шрифта.
 */
const FRACTIONS: ReadonlyMap<string, string> = new Map([
  ["1/2", "\u00BD"], // ½
  ["1/3", "\u2153"], // ⅓
  ["2/3", "\u2154"], // ⅔
  ["1/4", "\u00BC"], // ¼
  ["3/4", "\u00BE"], // ¾
  ["1/5", "\u2155"], // ⅕
  ["2/5", "\u2156"], // ⅖
  ["3/5", "\u2157"], // ⅗
  ["4/5", "\u2158"], // ⅘
  ["1/6", "\u2159"], // ⅙
  ["5/6", "\u215A"], // ⅚
  ["1/8", "\u215B"], // ⅛
  ["3/8", "\u215C"], // ⅜
  ["5/8", "\u215D"], // ⅝
  ["7/8", "\u215E"], // ⅞
]);

/**
 * Обыкновенные дроби.
 *
 * Записи вида «1/2» и «3/4» заменяются готовыми символами (½, ¾ и др.).
 * Неизвестная дробь остаётся как есть — правило консервативное.
 *
 * Защита от ложных срабатываний:
 *  - слэш должен стоять ровно между двумя числами и не примыкать к другим
 *    числам, слэшам и точкам: «11/2», «1/2/3», «1.1/2» не трогаются;
 *  - пробелы вокруг слэша допустимы («1 / 2») — они схлопываются при
 *    замене на символ дроби; неизвестная дробь остаётся как есть;
 *  - URL, даты, IP и версии защищены токенами раньше и сюда не попадают;
 *  - конструкции из слов («Мбит/сек») не затрагиваются: нужны цифры.
 */
export const fractionsRule: TypographyRule = {
  id: "fractions",
  name: "Обыкновенные дроби",
  description:
    "Заменяет записи вида «1/2» и «3/4» (в том числе с пробелами: «1 / 2») на символы ½ и ¾. Неизвестные дроби, URL, даты и конструкции вида «Мбит/сек» не трогаются.",
  category: "symbols",
  enabledByDefault: true,
  apply(text, ctx) {
    return applyRegex(
      ctx,
      fractionsRule,
      text,
      /(?<![\d/.])(\d+)[ \t]?\/[ \t]?(\d+)(?![\d/])/g,
      (m) => FRACTIONS.get(`${m[1]}/${m[2]}`) ?? m[0],
    );
  },
};