import type { TypographyRule } from "../types";
import { alternation, applyRegex } from "./helpers";

/**
 * Список распространённых единиц измерения. Используется правилом
 * «units-spacing» (пробел после числа) и правилом «nbsp-units»
 * (неразрывный пробел). Обновляется в одном месте.
 */
export const UNITS: readonly string[] = [
  "км", "см", "мм", "дм", "м",
  "кг", "мг", "г", "т",
  "л", "мл",
  "кВт", "МВт", "мВт", "Вт",
  "кВ", "мВ", "В",
  "мА", "мкА", "А",
  "ГГц", "МГц", "кГц", "Гц",
  "кДж", "Дж", "ккал",
  "ТБ", "ГБ", "МБ", "КБ",
  "Гбит", "Мбит", "Кбит", "бит", "байт",
  "мин", "сек", "ч", "с",
  "руб", "коп",
];

const UNITS_RE = new RegExp(
  "(\\d)(" + alternation(UNITS) + ")(?![\\p{L}\\p{N}])",
  "gu",
);

/**
 * Единицы измерения: гарантирует один пробел между числом и единицей,
 * если они «слиплись»: «10кг» → «10 кг», «5ч» → «5 ч».
 * Слово «мгновений» после «5» не трогается — проверяется следующий символ.
 */
export const unitsSpacingRule: TypographyRule = {
  id: "units-spacing",
  name: "Единицы измерения",
  description:
    "Отделяет единицы измерения от числа пробелом («10кг» → «10 кг», «1500м2» → «1500 м²»), убирает пробелы вокруг слэша между единицами («Мбит / сек» → «Мбит/сек»). Единицы, совпадающие с началом слова («5 мгновений»), не трогаются.",
  category: "units",
  enabledByDefault: true,
  apply(text, ctx) {
    const alt = alternation(UNITS);
    // «Мбит / сек» → «Мбит/сек»: слэш между единицами не отбивается пробелами.
    let result = applyRegex(
      ctx,
      unitsSpacingRule,
      text,
      new RegExp(
        `(?<![\\p{L}\\p{N}])(${alt})[ \\t\\u00A0]*\\/[ \\t\\u00A0]*(?=${alt}(?![\\p{L}\\p{N}]))`,
        "gu",
      ),
      (m) => m[1] + "/",
    );
    // Квадратные и кубические метры: «1500м2» → «1500 м²», «5 м3» → «5 м³».
    result = applyRegex(
      ctx,
      unitsSpacingRule,
      result,
      /(\d)[ \t\u00A0]?(м|км|см|мм|дм)[ \t\u00A0]?([23])(?![\p{L}\p{N}\u00B2\u00B3])/gu,
      (m) => `${m[1]} ${m[2]}${m[3] === "2" ? "\u00B2" : "\u00B3"}`,
    );
    return applyRegex(ctx, unitsSpacingRule, result, UNITS_RE, (m) => m[1] + " " + m[2]);
  },
};

/**
 * Температура и градусы.
 *  - «20°C», «20 ° С», «20°С» → «20 °C» (нормализуем пробел и символ);
 *  - «20 градусов Цельсия», «20 град. C» → «20 °C»;
 *  - аналогично для Фаренгейта → «°F».
 * Голое «20 градусов» не изменяется: нет уверенности, что это температура.
 */
export const temperatureRule: TypographyRule = {
  id: "temperature",
  name: "Температура и градусы",
  description:
    "Приводит обозначения температуры к виду «20 °C» / «20 °F» и нормализует запись «20 градусов Цельсия» → «20 °C».",
  category: "units",
  enabledByDefault: true,
  apply(text, ctx) {
    let result = applyRegex(
      ctx,
      temperatureRule,
      text,
      /(?<=\d)([ \t\u00A0]*)°[ \t\u00A0]*([CFСF])(?![\p{L}\p{N}])/gu,
      (m) => {
        // Сохраняем неразрывный пробел, если он уже был (идемпотентность).
        const lead = m[1] === "\u00A0" ? "\u00A0" : " ";
        return lead + "\u00B0" + (m[2] === "\u0421" ? "C" : m[2]);
      },
    );
    result = applyRegex(
      ctx,
      temperatureRule,
      result,
      /(?<=\d)[ \t\u00A0]*(?:град\.?|градус|градуса|градусов)[ \t\u00A0]+((?:по[ \t\u00A0]+)?(?:Цельси[юя]|Фаренгейт[уа])|[CFСFФ])(?![\p{L}\p{N}])/gu,
      (m) => (" \u00B0" + (/[FФ]/.test(m[1]) ? "F" : "C")),
    );
    return result;
  },
};
