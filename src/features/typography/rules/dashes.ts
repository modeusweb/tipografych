import type { TypographyRule } from "../types";
import { alternation, applyRegex, isAlphanumeric } from "./helpers";

const isDigit = (char: string | undefined): boolean => char !== undefined && /\d/.test(char);

/**
 * Дефисные местоимения и наречия, которые часто разрывают пробелами
 * («кто - то», «какая - либо», «всё - таки», «во - первых», «наконец - то»).
 *
 * Оба списка закрытые: склеиваются только заведомые дефисные слова.
 * Тире-конструкции не страдают — «Он не пришёл - то есть соврал»
 * остаётся тире, потому что «пришёл» в списке не состоит.
 */
const HYPHEN_WORD_LEFT: readonly string[] = [
  "кто", "что", "какой", "какая", "какое", "какие", "каков", "чей",
  "чья", "чьё", "чьи", "где", "куда", "откуда", "когда", "почему",
  "зачем", "как", "сколько", "насколько", "настолько", "кое", "всё",
  "все", "ну", "во", "в", "давным", "наконец", "опять", "давай", "смотри",
];

/** Правая часть: частицы и вторые части наречий («-то», «-либо», «-таки»). */
const HYPHEN_WORD_RIGHT: readonly string[] = [
  "то", "либо", "нибудь", "ка", "таки", "де", "давно",
  "первых", "вторых", "третьих", "четвёртых", "пятых", "шестых",
  "седьмых", "восьмых", "девятых", "десятых",
];

/** «кто - то» → «кто-то»: пробелы вокруг дефиса схлопываются. */
const BROKEN_HYPHEN_RE = new RegExp(
  "(?<![\\p{L}\\p{N}-])(" +
    alternation(HYPHEN_WORD_LEFT) +
    ")[ \\t]+-{1,2}[ \\t]+(" +
    alternation(HYPHEN_WORD_RIGHT) +
    ")(?![\\p{L}\\p{N}])",
  "giu",
);

/**
 * «как- либо», «что- то», «во- первых» → «как-либо», «что-то», «во-первых»:
 * пробел только ПОСЛЕ дефиса, перед ним дефис приклеен к слову.
 * Те же закрытые списки, что и у BROKEN_HYPHEN_RE, поэтому тире
 * («Он пришёл - проверить») не затрагивается. Идемпотентно: после
 * склейки пробела после дефиса нет.
 */
const BROKEN_HYPHEN_AFTER_RE = new RegExp(
  "(?<![\\p{L}\\p{N}-])(" +
    alternation(HYPHEN_WORD_LEFT) +
    ")-{1,2}[ \\t]+(" +
    alternation(HYPHEN_WORD_RIGHT) +
    ")(?![\\p{L}\\p{N}])",
  "giu",
);

/** «точь - в - точь» → «точь-в-точь». */
const TOCH_V_TOCH_RE =
  /([Тт]очь)[ \t]+-{1,2}[ \t]+([Вв])[ \t]+-{1,2}[ \t]+([Тт]очь)(?![\p{L}])/gu;

/**
 * Повтор слова («тихо - тихо», «едва - едва») → дефисное слово
 * («тихо-тихо», «едва-едва»). Совпадение обеих частей без учёта
 * регистра — это удвоение, а не тире. Разные слова («Любишь - люби»)
 * не склеиваются: тире-конструкция остаётся. Идемпотентно: после
 * склейки пробелов вокруг дефиса нет.
 */
const WORD_REPEAT_RE =
  /(?<![\p{L}\p{N}-])([\p{L}]+)[ \t]+-{1,2}[ \t]+([\p{L}]+)(?![\p{L}\p{N}])/giu;

/**
 * «Дефис-это» → «Дефис — это»: тире между словом и следующим за ним
 * «это» (подлежащее и сказуемое, набранные через дефис без пробелов).
 * Дефисные слова не страдают: в «кто-то» и «какой-либо» после дефиса
 * стоит не «это», а «то»/«либо»; «соглашение-этоовраг» отсечено
 * lookahead'ом (после «это» идёт буква).
 */
const WORD_ITO_RE = /(?<=[\p{L}\p{N}])-(?=[Ээ]то(?![\p{L}]))/gu;

/** «Ну привет,- ответила» → «Ну привет, — ответила»: дефис, прижатый к запятой, — тире. */
const COMMA_DASH_RE = /,(?:[ \t]*-{1,2})+[ \t]+(?=\S)/g;

/** Реплика диалога: «- Привет!» → «— Привет!». */
const LINE_START_DASH_RE = /^[ \t]*-{1,2}[ \t]+(?=\S)/gm;

/**
 * Латинские аббревиатуры-префиксы сложных слов: «IT-индустрия»,
 * «B2B-маркетинг», «VIP-зал», «HTTP-запрос». Левая часть — только
 * капс латиницы/цифр (2–8 знаков): «Instagram - популярная соцсеть»
 * с латинским словом в смешанном регистре не склеивается.
 *
 * Правая часть проверяется по списку служебных слов: «HTTP - это
 * протокол» — настоящее тире и остаётся тире.
 */
const LATIN_PREFIX_RE = new RegExp(
  "(?<![\\p{L}\\p{N}-])([A-Z][A-Z0-9]{1,7})[ \\t]+-{1,2}[ \\t]+([а-яёa-z]+)(?![\\p{L}\\p{N}])",
  "gu",
);

/** После этих слов тире — настоящее сказуемое, а не часть дефисного слова. */
const LATIN_PREFIX_EXCLUDE = new Set([
  "это", "что", "как", "не", "ни", "и", "а", "но", "то", "же", "бы", "ли",
  "есть", "был", "была", "было", "были", "будет", "будут", "все", "всё",
  "весь", "вся", "они", "он", "она", "оно", "мы", "вы", "ты", "я", "кто",
  "у", "к", "в", "с", "со", "по", "для", "при", "из", "от", "до", "на",
  "за", "о", "об", "там", "тут", "уже", "еще", "ещё", "так", "только",
  "даже", "или", "либо",
]);

/**
 * Тире.
 *
 * dash-sentence — тире в предложении: дефис, окружённый пробелами,
 * превращается в длинное тире («Он сказал - привет» → «Он сказал — привет»).
 *  - не трогает диапазоны «10 - 20» (их доводит до ума правило диапазонов);
 *  - не трогает «--flag», файлы и email — они защищены токенами;
 *  - заодно подклеивает пробелы к «слипшемуся» тире («слово—слово»).
 *
 * dash-ranges — диапазоны: «10-20», «2020-2025» → «10–20», «2020–2025»
 * (короткое тире без пробелов). Телефоны, даты, IP и версии защищены
 * раньше правил, поэтому не пострадают.
 */
export const dashSentenceRule: TypographyRule = {
  id: "dash-sentence",
  name: "Тире в предложениях",
  description:
    "Превращает дефис с пробелами в длинное тире («Он сказал - привет» → «Он сказал — привет»), склеивает разорванные дефисные слова («кто - то», «как- либо» → «кто-то», «как-либо»), правит «Дефис-это» → «Дефис — это», «привет,-» → «привет, —» и реплики диалога «- Привет!» → «— Привет!», убирает висячие дефисы и добавляет пробелы к слипшемуся тире.",
  category: "dashes",
  enabledByDefault: true,
  apply(text, ctx) {
    // Дефисные слова, разорванные пробелами: «кто - то», «точь - в - точь».
    // Это опечатка, а не тире — слово склеивается дефисом.
    let result = applyRegex(
      ctx,
      dashSentenceRule,
      text,
      TOCH_V_TOCH_RE,
      (m) => `${m[1]}-${m[2]}-${m[3]}`,
    );
    // Повторы слов: «тихо - тихо» → «тихо-тихо» (дефис, а не тире).
    result = applyRegex(ctx, dashSentenceRule, result, WORD_REPEAT_RE, (m) =>
      m[1].toLowerCase() === m[2].toLowerCase() ? `${m[1]}-${m[2]}` : m[0],
    );
    result = applyRegex(ctx, dashSentenceRule, result, BROKEN_HYPHEN_RE, (m) => `${m[1]}-${m[2]}`);
    // Латинский префикс: «IT - индустрии» → «IT-индустрии». Дефис здесь
    // часть сложного слова, а тире-прочтение («HTTP - это протокол»)
    // отсекается списком служебных слов.
    result = applyRegex(ctx, dashSentenceRule, result, LATIN_PREFIX_RE, (m) => {
      if (LATIN_PREFIX_EXCLUDE.has(m[2].toLowerCase())) return m[0];
      return `${m[1]}-${m[2]}`;
    });
    result = applyRegex(
      ctx,
      dashSentenceRule,
      result,
      BROKEN_HYPHEN_AFTER_RE,
      (m) => `${m[1]}-${m[2]}`,
    );
    // «Дефис-это» → «Дефис — это»: тире между словом и «это».
    result = applyRegex(ctx, dashSentenceRule, result, WORD_ITO_RE, () => "\u00A0\u2014 ");
    // «Ну привет,- ответила» → «Ну привет, — ответила».
    result = applyRegex(ctx, dashSentenceRule, result, COMMA_DASH_RE, () => ",\u00A0\u2014 ");
    // Реплика диалога: «- Привет!» → «— Привет!». В Markdown дефис в начале
    // строки — маркер списка, поэтому там не трогается.
    if (ctx.options.format !== "markdown") {
      result = applyRegex(ctx, dashSentenceRule, result, LINE_START_DASH_RE, () => "\u2014 ");
    }
    // Перечислительные наречия: «Во-вторых-найти» → «Во-вторых — найти».
    // Только закрытый список наречий: дефис внутри обычных сложных слов
    // («красно-белый») не трогаем. Идемпотентно: после замены дефиса нет.
    result = applyRegex(
      ctx,
      dashSentenceRule,
      result,
      /((?:[Вв]о-(?:первых|вторых|третьих|четвёртых|пятых|шестых|седьмых|восьмых|девятых|десятых))|(?:[Вв]-(?:третьих|четвёртых|пятых|шестых|седьмых|восьмых|девятых|десятых)))-(?=[А-ЯЁа-яёA-Za-z])/g,
      (m) => `${m[1]}${String.fromCharCode(0xa0, 0x2014)} `,
    );
    // Висячий дефис: пробел перед дефисом, но не после («тест -драйв» → «тест-драйв»).
    // Только если после дефиса БУКВА (не цифра!) — иначе это отрицательное число.
    result = applyRegex(
      ctx,
      dashSentenceRule,
      result,
      /(?<=\S)[ \t]+-{1,2}(?=\p{L})/gu,
      () => "-",
    );
    result = applyRegex(
      ctx,
      dashSentenceRule,
      result,
      // Цепочки дефисов (« - - ») захватываются целиком, чтобы
      // повторная обработка была идемпотентной.
      /(?<=\S)(?:[ \t]+-{1,2})+[ \t]+(?=\S)/g,
      (m) => {
        const prev = result.charAt(m.index - 1);
        const next = result.charAt(m.index + m[0].length);
        if (isDigit(prev) && isDigit(next)) return m[0]; // диапазон — см. dash-ranges
        return "\u00A0— ";
      },
    );
    result = applyRegex(
      ctx,
      dashSentenceRule,
      result,
      /([\p{L}\p{N}»"”)\u2026])\u2014(?=[\p{L}\p{N}«“(])/gu,
      (m) => {
        const prev = m[1];
        const next = result.charAt(m.index + m[0].length);
        if (isDigit(prev) && isDigit(next)) return m[0];
        return prev + " \u2014";
      },
    );
    return result;
  },
};

export const dashRangesRule: TypographyRule = {
  id: "dash-ranges",
  name: "Диапазоны",
  description:
    "Заменяет дефис в числовых диапазонах на короткое тире («2020-2025» → «2020–2025»), в том числе в римских веках с контекстом («XVI-XVII веках» → «XVI–XVII»). Дефисы внутри слов и идентификаторы не трогаются.",
  category: "dashes",
  enabledByDefault: true,
  apply(text, ctx) {
    let result = applyRegex(ctx, dashRangesRule, text, /(?<=\d)[ \t]?-[ \t]?(?=\d)/g, () => "\u2013");
    result = applyRegex(ctx, dashRangesRule, result, /(?<=\d)[\u2013\u2014](?=\d)/g, () => "\u2013");
    // Римские века/столетия с явным контекстом: «XVI-XVII веках»,
    // «XX - XXI век» → «XVI–XVII», «XX–XXI». Без контекста («XX-XXI»)
    // не трогаем: аббревиатуры из римских букв (LCD, MIX, DIM) встречаются
    // и в другом значении.
    result = applyRegex(
      ctx,
      dashRangesRule,
      result,
      /(?<![IVXLCDM])([IVXLCDM]{1,6})[ \t\u00A0]*[-\u2014][ \t\u00A0]*([IVXLCDM]{1,6})(?![IVXLCDM])(?=[ \t\u00A0]+(?:вв?\.|век[а-яё]*|столет[а-яё]*))/g,
      (m) => `${m[1]}\u2013${m[2]}`,
    );
    return result;
  },
};

/**
 * Минус.
 *
 * minus-sign — дефис, который стоит сразу перед числом и не является
 * частью диапазона, превращается в типографский минус U+2212
 * («-10 °C» → «−10 °C»): по высоте он совпадает с плюсом.
 *  - не трогает диапазоны «5-6» (перед дефисом цифра — это работа dash-ranges);
 *  - не трогает идентификаторы «ISO-8601», «UTF-8», «RS-232» (перед дефисом буква);
 *  - не трогает цепочки «--10» (двойной дефис) и телефоны — они защищены токенами.
 */
export const minusSignRule: TypographyRule = {
  id: "minus-sign",
  name: "Знак минуса",
  description:
    "Заменяет дефис перед числом на типографский минус («-10 °C» → «−10 °C»). Диапазоны («5-6»), телефоны и идентификаторы («ISO-8601») не трогаются.",
  category: "dashes",
  enabledByDefault: true,
  apply(text, ctx) {
    // Дефис сразу перед цифрой, но НЕ после буквы, цифры или другого дефиса:
    // иначе это диапазон, идентификатор или «слипшийся» двойной дефис.
    return applyRegex(ctx, minusSignRule, text, /(?<![\d\p{L}-])-(?=\d)/gu, () => "\u2212");
  },
};

export { isAlphanumeric };
