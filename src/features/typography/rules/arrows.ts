import type { TypographyRule } from "../types";
import { applyRegex } from "./helpers";

/**
 * Стрелки.
 *
 * Текстовые стрелки заменяются символами:
 *   «->» → «\u2192», «<-» → «\u2190», «<=>» → «\u21D4».
 *
 * Защита от ложных срабатываний:
 *  - «-->», «->>» и «<<-» не трогаются: это или фрагмент кода, или
 *    составная последовательность;
 *  - «<--» и «<!--» не трогаются (HTML-комментарии обычно и так защищены
 *    токенами, но правило не должно зависеть от настроек защиты);
 *  - одиночные «<» и «>» не затрагиваются.
 */
export const arrowsRule: TypographyRule = {
  id: "arrows",
  name: "Стрелки",
  description:
    "Заменяет текстовые стрелки «->», «<-» и «<=>» на символы →, ← и ⇔. Многосимвольные последовательности вида «-->» не трогаются.",
  category: "symbols",
  enabledByDefault: true,
  apply(text, ctx) {
    // «⇔» проверяем первым: иначе «<-» внутри «<=>» не найдётся, но
    // порядок делает намерение явным.
    let result = applyRegex(ctx, arrowsRule, text, /(?<!<)<=>(?!>)/g, () => "\u21D4");
    result = applyRegex(ctx, arrowsRule, result, /(?<!-)->(?![->])/g, () => "\u2192");
    return applyRegex(ctx, arrowsRule, result, /(?<!<)<-(?![-!])/g, () => "\u2190");
  },
};